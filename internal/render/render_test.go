func TestMissingKeyNamesTemplateAndLine(t *testing.T) {
	src := []byte("line1\nline2 {{.missingField}}\nline3\n")
	tmpl, err := render.Parse("generator.go.tmpl", src)
	if err != nil {
		t.Fatalf("parse error: %v", err)
	}

	_, err = tmpl.Execute(map[string]any{"existing": "value"})
	if err == nil {
		t.Fatal("expected error on missing key, got nil")
	}

	errMsg := err.Error()
	if !strings.Contains(errMsg, "generator.go.tmpl") {
		t.Errorf("error does not name template file:\ngot: %s", errMsg)
	}
	if !strings.Contains(errMsg, "generator.go.tmpl:2:") {
		t.Errorf("error does not name line 2:\ngot: %s", errMsg)
	}
	if !strings.Contains(errMsg, "missingField") {
		t.Errorf("error does not name missing key:\ngot: %s", errMsg)
	}
}

