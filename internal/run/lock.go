package run

import (
	"errors"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/epistemer/genx/internal/paths"
)

// LockFile is the list of files genx wrote, at the module root
// (interface.md §8).
const LockFile = "genx.lock"

const lockHeader = "# Code generated by genx. DO NOT EDIT.\n# The files genx wrote, and the generator that wrote each.\n"

// lock is the list of files generators wrote: path → step.
type lock struct {
	exists bool
	steps  map[string]string
}

// readLock reads genx.lock; a missing lock is an empty one.
func (s *state) readLock() (lock, error) {
	l := lock{steps: map[string]string{}}
	b, err := s.root.ReadFile(LockFile)
	if errors.Is(err, os.ErrNotExist) {
		return l, nil
	}
	if err != nil {
		return l, err
	}
	l.exists = true
	for n, line := range strings.Split(strings.ReplaceAll(string(b), "\r\n", "\n"), "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		p, step, ok := strings.Cut(line, " ")
		pkg, gen, colon := strings.Cut(step, ":")
		if !ok || !colon || pkg == "" || gen == "" || strings.ContainsAny(step, " \t") || strings.Contains(gen, ":") {
			return l, fmt.Errorf("%s:%d: want \"<path> <package>:<generator>\", got %q", LockFile, n+1, line)
		}
		if clean, err := paths.Out(p); err != nil {
			return l, fmt.Errorf("%s:%d: %w", LockFile, n+1, err)
		} else if clean != p {
			return l, fmt.Errorf("%s:%d: %q isn't clean (use %q)", LockFile, n+1, p, clean)
		}
		if l.has(p) {
			return l, fmt.Errorf("%s:%d: %s is listed twice", LockFile, n+1, p)
		}
		l.steps[p] = step
	}
	return l, nil
}

// has reports whether the lock lists p, compared without case.
func (l lock) has(p string) bool {
	key := paths.Fold(p)
	for q := range l.steps {
		if paths.Fold(q) == key {
			return true
		}
	}
	return false
}

// sorted returns the lock's paths in byte order.
func (l lock) sorted() []string {
	ps := make([]string, 0, len(l.steps))
	for p := range l.steps {
		ps = append(ps, p)
	}
	sort.Strings(ps)
	return ps
}

// encode is the lock's file content.
func (l lock) encode() []byte {
	var b strings.Builder
	b.WriteString(lockHeader)
	for _, p := range l.sorted() {
		fmt.Fprintf(&b, "%s %s\n", p, l.steps[p])
	}
	return []byte(b.String())
}

// newLock is the lock this run's outputs make.
func (s *state) newLock() lock {
	l := lock{steps: map[string]string{}}
	for _, o := range s.outputs {
		l.steps[o.path] = o.step
	}
	return l
}
